"""Builds the delta constellation for scene 16.

    python -I build_constellation.py <package dir> [--show]

Writes ArtDelta3D.txt: a solid ∆ of stars and faint lines (front, edges, back), one view per place that sees it.
--show prints each view.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Exporter

TRI = [(0.0, 1.0), (-0.87, -0.5), (0.87, -0.5)]
DEPTH = 0.42
VERTS = [(x, y, DEPTH) for x, y in TRI] + [(x, y, -DEPTH) for x, y in TRI]
FRONT = [(0, 1), (1, 2), (2, 0)]
SIDES = [(0, 3), (1, 4), (2, 5)]
BACK = [(3, 4), (4, 5), (5, 3)]
EDGES = [(a, b, 0) for a, b in FRONT] + [(a, b, 1) for a, b in SIDES] + [(a, b, 2) for a, b in BACK]
# yaw, pitch, roll (degrees) and columns and rows per unit for each view: the far mountain (biggest), the mine's
# mouth, and the three montage places
VIEWS = [(24, -16, 0, 15.0, 6.8), (-34, -22, 7, 13.0, 5.8), (58, -10, -5, 12.0, 5.4),
         (-62, -30, 4, 12.0, 5.4), (12, -38, -8, 12.0, 5.4)]
F = 6.0                     # how far off it is, for its perspective


def turn(v, yaw, pitch, roll):
    x, y, z = v
    a, b, c = math.radians(yaw), math.radians(pitch), math.radians(roll)
    x, z = x * math.cos(a) + z * math.sin(a), -x * math.sin(a) + z * math.cos(a)
    y, z = y * math.cos(b) - z * math.sin(b), y * math.sin(b) + z * math.cos(b)
    x, y = x * math.cos(c) - y * math.sin(c), x * math.sin(c) + y * math.cos(c)
    return x, y, z


def cells(x0, y0, x1, y1):
    """The cells on the way from one star to the other, not counting either."""
    out = []
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
    err = dx + dy
    x, y = x0, y0
    while (x, y) != (x1, y1):
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x += sx
        if e2 <= dx:
            err += dx
            y += sy
        out.append((x, y))
    return out[:-1]


def glyph(prev, nxt):
    dx, dy = nxt[0] - prev[0], nxt[1] - prev[1]
    if dy == 0:
        return "-"
    if dx == 0:
        return "|"
    return "\\" if dx * dy > 0 else "/"


def view(yaw, pitch, roll, sx, sy):
    pts = []
    for v in VERTS:
        x, y, z = turn(v, yaw, pitch, roll)
        k = F / (F + z)
        pts.append((x * k * sx, -y * k * sy))
    # the front edges' middles
    mids = []
    for a, b in FRONT:
        mids.append(((pts[a][0] + pts[b][0]) / 2, (pts[a][1] + pts[b][1]) / 2))
    allp = pts + mids
    x0 = min(p[0] for p in allp)
    y0 = min(p[1] for p in allp)
    stars = [(int(round(p[0] - x0)) + 1, int(round(p[1] - y0)) + 1) for p in allp]
    kinds = [0] * 6 + [1] * 3
    lines = []
    ends = []
    # each front edge goes through its middle star, so it's drawn as two halves
    for a, b, cls in EDGES:
        path = [stars[a]]
        if cls == 0:
            path.append(stars[6 + FRONT.index((a, b))])
        path.append(stars[b])
        for p, q in zip(path, path[1:]):
            run = [p] + cells(p[0], p[1], q[0], q[1]) + [q]
            for i in range(1, len(run) - 1):
                c = run[i]
                if c in stars or any((c[0], c[1]) == (l[0], l[1]) for l in lines):
                    continue
                # the back ∆ is dotted
                lines.append((c[0], c[1], "." if cls == 2 else glyph(run[i - 1], run[i + 1]), cls))
        ends.append(len(lines))
    w = max(s[0] for s in stars) + 2
    h = max(s[1] for s in stars) + 2
    return w, h, stars, kinds, lines, ends


def show(w, h, stars, lines):
    g = [[" "] * w for _ in range(h)]
    for x, y, ch, cls in lines:
        g[y][x] = ch
    for x, y in stars:
        g[y][x] = "*"
    print("\n".join("".join(r) for r in g))


def main():
    pkg = sys.argv[1]
    ex = Exporter("// Generated by tools/build_constellation.py. Don't edit by hand; change the script and rebuild.\n")
    ex.value("views", len(VIEWS))
    for k, v in enumerate(VIEWS):
        w, h, stars, kinds, lines, ends = view(*v)
        if "--show" in sys.argv:
            print(f"view {k}: {w} x {h}, {len(lines)} line cells")
            show(w, h, stars, lines)
        ex.value(f"w{k}", w)
        ex.value(f"h{k}", h)
        ex.value(f"starX{k}", [s[0] for s in stars])
        ex.value(f"starY{k}", [s[1] for s in stars])
        ex.value(f"starKind{k}", kinds)
        ex.value(f"lineX{k}", [l[0] for l in lines])
        ex.value(f"lineY{k}", [l[1] for l in lines])
        ex.value(f"lineClass{k}", [l[3] for l in lines])
        ex.value(f"edgeEnd{k}", ends)
        # glyphs as one ascii block so backslashes aren't escapes (the game only breaks a line on a backslash-n)
        glyphs = "".join(l[2] for l in lines)
        assert "\\n" not in glyphs
        ex.parts.append(f"var lineS{k} = ascii\n" + glyphs + "\nasciiend\n")
    # not cropped, the game's rainbow runs across the page
    ex.piece("star", __import__("build_scene1").frames_of([["."], ["+"], ["*"], ["+"]], "#ffffff"), crop=False)
    n = ex.write(os.path.join(pkg, "ArtDelta3D.txt"))
    print(f"ArtDelta3D {n} bytes")


if __name__ == "__main__":
    main()
