"""Builds the title card's art (Deltahead/ArtTitle.txt).

    python -I build_title.py <package dir>

Title.txt builds the lettering out of Ki motes, so for every cell this works out its glyph, where its mote rises
from, and when it arrives and leaves.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Grid, Exporter

SLAB = {
    "E": [".----.", "| .--'", "| '--.", "| .--'", "'----'"],
    "L": [".-.   ", "| |   ", "| |   ", "| '--.", "'----'"],
    "T": [".-----.", "'-. .-'", "  | |  ", "  | |  ", "  '-'  "],
    "A": ["  .^.  ", " / . \\ ", "/ /_\\ \\", "| .-. |", "'-' '-'"],
    "H": [".-. .-.", "| | | |", "| '-' |", "| .-. |", "'-' '-'"],
    "D": [".----. ", "| .-. \\", "| | | |", "| '-' /", "'----' "],
}
DELTA = ["     .^.     ", "    / ^ \\    ", "   / / \\ \\   ", "  / /   \\ \\  ", " / '-----' \\ ",
         "'-----------'"]
TOP = "O N E   M U S T   I M A G I N E   T H E"
KERN = {("L", "T"): -2, ("T", "A"): -1}
BOTTOM = "H A P P Y"

# mote timing in frames from the card's start: the music lifts at about 13 s and hits at 21 s,
# so the words gather through the lift and the ∆ is whole on the hit
FLY = 100
ARRIVE = {"top": (400, 470), "word": (430, 590), "bottom": (560, 610), "delta": (575, 628)}
LEAVE = {"top": (800, 840), "word": (815, 875), "bottom": (845, 870), "delta": (900, 900)}


def layout():
    """[(x, y, glyph, part)] for every drawn cell, the card's width and height, and where the ∆ is."""
    # a space between letters, but LT and TA close up where their shapes leave room
    grid = {}
    for j, row in enumerate(DELTA):
        for i, ch in enumerate(row):
            if ch != " ":
                grid[(i, j)] = ch
    x = len(DELTA[0]) + 1
    prev = None
    for ch in "ELTAHEAD":
        x += KERN.get((prev, ch), 0)
        for j, row in enumerate(SLAB[ch]):
            for i, c in enumerate(row):
                if c != " ":
                    grid[(x + i, j + 1)] = c
        x += len(SLAB[ch][0]) + 1
        prev = ch
    width = max(i for i, _ in grid) + 1
    rows = ["".join(grid.get((i, j), " ") for i in range(width)).rstrip() for j in range(6)]
    w = max(len(r) for r in rows)
    cells = []
    for i, ch in enumerate(TOP.center(w)):
        if ch != " ":
            cells.append((i, 0, ch, "top"))
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch != " ":
                cells.append((i, 2 + j, ch, "delta" if i < len(DELTA[0]) else "word"))
    for i, ch in enumerate(BOTTOM.center(w)):
        if ch != " ":
            cells.append((i, 9, ch, "bottom"))
    return cells, w, 10, (0, 2)


def main():
    pkg = sys.argv[1]
    r = random.Random(77)
    cells, w, h, (dx, dy) = layout()
    xs = {p: [c[0] for c in cells if c[3] == p] for p in ARRIVE}
    arrive, leave, rise = [], [], []
    for x, y, ch, p in cells:
        lo, hi = min(xs[p]), max(xs[p])
        u = (x - lo) / max(1, hi - lo)
        a0, a1 = ARRIVE[p]
        # a loose sweep from the left so it doesn't read as a wipe. the ∆ fills in from its foot up
        if p == "delta":
            u = 1 - (y - dy) / 5.0
        arrive.append(int(round(a0 + (a1 - a0) * (0.65 * u + 0.35 * r.random()))))
        l0, l1 = LEAVE[p]
        leave.append(int(round(l0 + (l1 - l0) * (0.6 * (1 - u) + 0.4 * r.random()))))
        rise.append(r.randint(-14, 14))
    # gaps between letters go dark while both sides are in, so no star shows through "H A P P Y"
    at = {(c[0], c[1]): i for i, c in enumerate(cells)}
    gaps = []
    for y in range(h):
        row = sorted(x for x, yy in at if yy == y)
        for xa, xb in zip(row, row[1:]):
            a, b = at[(xa, y)], at[(xb, y)]
            for x in range(xa + 1, xb):
                gaps.append((x, y, max(arrive[a], arrive[b]), min(leave[a], leave[b])))
    ex = Exporter("// Generated by tools/build_title.py. Don't edit by hand; change the script and rebuild.\n")
    ex.value("w", w)
    ex.value("h", h)
    ex.value("cellX", [c[0] for c in cells])
    ex.value("cellY", [c[1] for c in cells])
    # glyphs in an ascii block so nothing reads as an escape (the game takes backslash n as a line break)
    glyphs = "".join(c[2] for c in cells)
    assert "\\n" not in glyphs
    ex.parts.append("var cellS = ascii\n" + glyphs + "\nasciiend\n")
    ex.value("arrive", arrive)
    ex.value("leave", leave)
    ex.value("riseDX", rise)
    ex.value("gapX", [g[0] for g in gaps])
    ex.value("gapY", [g[1] for g in gaps])
    ex.value("gapFrom", [g[2] for g in gaps])
    ex.value("gapTo", [g[3] for g in gaps])
    ex.value("gapFirst", min(g[2] for g in gaps))
    ex.value("gapLast", max(g[3] for g in gaps))
    ex.value("fly", FLY)
    ex.value("nTop", sum(1 for c in cells if c[3] == "top"))
    ex.value("lightAt", ARRIVE["delta"][1] + 2)
    ex.value("deltaLeaves", LEAVE["delta"][0])
    # the ∆ alone, lit in rainbow over the motes' one. solid so no star shows through as it rises away
    g = Grid(len(DELTA[0]), len(DELTA))
    g.solid(0, 0, DELTA, "#ffffff")
    # uncropped since the rainbow runs across the page
    ex.piece("delta", [g], crop=False)
    ex.value("deltaX", dx)
    ex.value("deltaY", dy)
    # a ring of sparks flying out as it lights
    sparks = []
    for k in range(6):
        s = Grid(34, 14)
        for i in range(16):
            a = i / 16 * 2 * math.pi
            rr = 2.5 + k * 1.7
            s.set(int(round(17 + rr * 2 * math.cos(a))), int(round(7 + rr * math.sin(a))),
                  "*+'.·"[min(4, k)] if (i + k) % 2 == 0 else "'.", "#ffffff")
        sparks.append(s)
    ex.piece("sparks", sparks)
    print("gaps", len(gaps))
    n = ex.write(os.path.join(pkg, "ArtTitle.txt"))
    print(f"ArtTitle {n} bytes, {w} x {h}, {len(cells)} cells")


if __name__ == "__main__":
    main()
