"""Builds the art for scene 15 (he wears the ∆).

    python -I build_scene15.py <package dir>

Writes Art15Rise.txt: his standing frame in three row bands for the rainbow shimmer, the Stream's band of light,
and the game's stowaway shake spread over 30 frames a second. Everything else comes from scene 14's art.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Exporter, frames_of
import bridge_frames as BF
from build_scene14 import HERO

BAND = "#c8ffd8"


def rows_of(frame, keep):
    """One frame of him with only the rows in `keep`, minus the O head (his ∆ is drawn on its own)."""
    return [row.replace("O", " ") if j in keep else " " * len(row) for j, row in enumerate(frame)]


def main():
    pkg = sys.argv[1]
    os.makedirs(pkg, exist_ok=True)
    head = "// Generated by tools/build_scene15.py. Don't edit by hand; change the script and rebuild.\n"
    ex = Exporter(head)
    stand = HERO[4]
    for name, keep in (("rowA", (0, 1)), ("rowB", (2,)), ("rowC", (3,))):
        # no crop, the game's rainbow runs across the whole page
        ex.piece(name, frames_of([rows_of(stand, keep)], "#ffffff"), crop=False)
    ex.piece("band", frames_of([["─" * 9]], BAND))
    n = len(BF.SHAKE) * 30 // BF.SHAKE_STEPS_PER_S
    ex.value("jig", [BF.SHAKE[j * BF.SHAKE_STEPS_PER_S // 30] for j in range(n)])
    size = ex.write(os.path.join(pkg, "Art15Rise.txt"))
    print(f"Art15Rise {size} bytes")


if __name__ == "__main__":
    main()
