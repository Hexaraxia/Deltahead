"""Builds the art for scene 10 (the Controller, crowned).

    python -I build_scene10.py <package dir>

Writes Art10Summit.txt: the snowfield on the mountain's shoulder, the summit up close, and the Controller as a gold
Monarch Dominotaur with his whip. The sky and rocks are scene 7's, him and the fight effects scene 8's.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Grid, Exporter, frames_of, TEX, ROCKC
from build_scene7 import SNOW, SNOW_DIM, SNOW_BACK, FOG_DIM, BACK, FRONT, crop, peak
import controller_frames as CTRLF
import whips

GOLD = "#d7af42"            # the game's Monarch tint

WW, WH = 240, 44
FEET0, FEET1 = 25, 22       # the shoulder climbs gently toward the summit


def feet(x):
    return FEET0 + (FEET1 - FEET0) * x / WW


def band(g, x, rr, row):
    """One column of the snowfield, as deep as scene 7's path."""
    sub = feet(x) - math.floor(feet(x))
    top = row - BACK
    g.set(x, top, "_" if rr.random() < 0.75 else rr.choice("-_."), SNOW_BACK)
    for y in range(top + 1, row + FRONT):
        g.blank(x, y, x, y, TEX)
        if rr.random() < 0.11:
            g.set(x, y, rr.choice("_-¯.'`"), SNOW_BACK if y < row else SNOW_DIM)
    g.set(x, row + FRONT, "¯" if sub < 0.34 else ("-" if sub < 0.67 else "_"), SNOW)


def build_field():
    """The snowfield, the rock under it down to the cloud, and drifts at its back."""
    r = random.Random(101)
    g = Grid(WW, WH)
    for x in range(WW):
        row = int(math.floor(feet(x)))
        band(g, x, r, row)
        depth = 8 + int(3 * math.sin(x * 0.12) + 2 * math.sin(x * 0.37))
        for y in range(row + FRONT + 1, min(WH, row + FRONT + depth)):
            g.blank(x, y, x, y, TEX)
            d = y - row - FRONT
            p = r.random()
            if d == 1 and p < 0.6:
                g.set(x, y, r.choice(".:'"), SNOW_DIM)
            elif d < 4 and p < 0.3:
                g.set(x, y, r.choice("|'!:"), ROCKC)
            elif p < 0.08:
                g.set(x, y, r.choice(".'`"), TEX)
        g.set(x, min(WH - 1, row + FRONT + depth), r.choice("'`.,"), FOG_DIM)
        if r.random() < 0.06:
            g.text(x, row - BACK - 1, r.choice((".-.", "_.~._", ",.-.", "_/¯\\_")), SNOW_BACK)
    return g


def build_summit():
    """The summit up close, with a smaller peak beside it."""
    r = random.Random(102)
    g = Grid(80, 16)
    h = 14
    peak(g, 46, 16, h, True, r, "#5c6672", "#7c8692", "#0e1216", lit_p=0.22)
    peak(g, 20, 16, 8, True, r, "#4a525c", "#5c6672", "#0c1013", lit_p=0.15)
    # snow on its head, down its ridges
    for y in range(16 - h, 16 - h + 5):
        k = y - (16 - h)
        for x in range(46 - k - 1, 46 + k + 1):
            if r.random() < 0.35:
                g.set(x, y, r.choice(".:'"), SNOW if x < 46 else SNOW_DIM)
    g.text(45, 16 - h, "/\\", SNOW)
    return g


def build_controller(ex):
    """The gold Dominotaur facing left, a frame holding just the whip handle (for while the lash is out), and the lash."""
    g = frames_of(CTRLF.DOMINO + [CTRLF.DOMINO_BARE], GOLD)
    ex.piece("ctrl", g)
    ex.value("ctrlW", g[0].w)
    ex.value("ctrlH", g[0].h)
    ex.value("ctrlBody0", CTRLF.DOMINO_BODY[0])
    ex.value("ctrlBody1", CTRLF.DOMINO_BODY[1])
    ex.value("ctrlHandX", CTRLF.DOMINO_HAND[0])
    ex.value("ctrlHandY", CTRLF.DOMINO_HAND[1])
    hand_y = CTRLF.DOMINO_HAND[1] - (g[0].h - 1)
    lg, lox, loy, crack = whips.lash(n=27, frames=22, ground=lambda dx: -0.79, hand_y=hand_y, dir=-1, col=GOLD,
                                     keep=8, v=2.0, gravity=0.05, scale=1.4)
    ex.piece("lash", lg)
    ex.value("lashOX", lox)
    ex.value("lashOY", loy)
    ex.value("lashCrack", crack)
    ex.value("lashN", len(lg))
    return lg, lox


def main():
    pkg = sys.argv[1]
    os.makedirs(pkg, exist_ok=True)
    head = "// Generated by tools/build_scene10.py. Don't edit by hand; change the script and rebuild.\n"
    ex = Exporter(head)
    ex.value("ww", WW)
    ex.value("feet0", FEET0)
    ex.value("feet1", FEET1)
    ex.value("floorFront", FRONT)
    field = build_field()
    ex.piece("fieldA", [crop(field, 0, 0, 120, WH)])
    ex.piece("fieldB", [crop(field, 120, 0, WW - 120, WH)])
    ex.piece("summit", [build_summit()])
    lg, lox = build_controller(ex)
    n = ex.write(os.path.join(pkg, "Art10Summit.txt"))
    print(f"Art10Summit {n} bytes; lash {len(lg)} frames, reaches {lox} left of his hand")


if __name__ == "__main__":
    main()
