"""Builds the art for scene 17 (Up, and the stinger).

    python -I build_scene17.py <package dir>

Writes Art17Up.txt: the moonlit sky, the cloud bank with the Stream's gap, the cloud tops and islands, him with his
Ice Sword, and the empty cart on a stub of rail back at the Ring.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Grid, Exporter, frames_of, CHAR, TEX, RAILC
from build_scene14 import HERO, ICE_BLADE

RAY = "#e8d8a0"
CART_RIM = "#9a9a9a"
CART_DIM = "#6e6e6e"
RAIL_LEN = 6


BANK_W = 170
BANK_GAP = 13                     # the gap the Stream comes up through, in the middle
DOT_DIM = "#2e2e2e"
DOT = "#565656"
EDGE = "#8a8a8a"


def puff(widths):
    """A puff of cloud like the game's: a little cap, a bigger body, a flat bottom trailing off."""
    a, b = widths
    rows = [" " * 2 + "_" * a, "_(" + " " * a + ")__", "(" + " " * (a + b) + ")__", "(" + "_" * (a + b + 2) + " _."]
    g = Grid(max(len(r) for r in rows), len(rows))
    for y, row in enumerate(rows):
        x0 = len(row) - len(row.lstrip(" "))
        x1 = len(row.rstrip(" ")) - 1
        if y > 0:
            g.blank(x0, y, min(x1, x0 + a + b + 2), y, "#000000")
        for x, ch in enumerate(row):
            if ch != " ":
                g.set(x, y, ch, EDGE if y < 3 else DOT)
    return g


def scallop(r, x):
    """How far a cloud's edge bulges at column x."""
    return int(round(1.3 * math.sin(x * 0.42) + 0.8 * math.sin(x * 0.17 + 1.3)))


def bank(front):
    """A bank of cloud right across the picture, stippled, its edge in little scallops; the front one hangs lower
    and is open in the middle for the Stream, the back one is whole."""
    r = random.Random(181 if front else 182)
    h = 12
    g = Grid(BANK_W, h)
    mid = BANK_W // 2
    for x in range(BANK_W):
        gap = front and abs(x - mid) <= BANK_GAP // 2 + (1 if abs(x - mid) > BANK_GAP // 2 - 2 else 0)
        if gap:
            continue
        top = 2 + scallop(r, x) if not front else 4 + scallop(r, x + 40)
        bot = h - 3 + scallop(r, x + 13) if not front else h - 1 + min(0, scallop(r, x + 7))
        if front and abs(x - mid) <= BANK_GAP // 2 + 4:
            top += 1
        for y in range(top, bot + 1):
            g.blank(x, y, x, y, "#000000")
            if r.random() < 0.42:
                g.set(x, y, ":" if r.random() < 0.6 else ".", DOT_DIM if y < bot - 1 else DOT)
        nt = (2 + scallop(r, x + 1)) if not front else (4 + scallop(r, x + 41))
        g.set(x, top, "_" if nt == top else ("(" if nt < top else ")"), EDGE)
        g.set(x, bot, "_", DOT)
    return g


def cloud_sea(w, h):
    """The tops of the cloud, seen from above them: a scalloped edge, stipple below."""
    r = random.Random(183)
    g = Grid(w, h)
    for x in range(w):
        top = 1 + scallop(r, x + 5)
        for y in range(top, h):
            g.blank(x, y, x, y, "#000000")
            if r.random() < 0.35:
                g.set(x, y, r.choice(":.'"), DOT_DIM)
        nt = 1 + scallop(r, x + 6)
        g.set(x, top, "_" if nt == top else ("(" if nt < top else ")"), EDGE)
    return g


def island(w, h, seed):
    """A cloud island floating up there: a domed top, a flat ragged underside, stippled inside."""
    r = random.Random(seed)
    g = Grid(w, h)
    for x in range(w):
        u = (x - (w - 1) / 2.0) / ((w - 1) / 2.0)
        top = int(round((h - 3) * abs(u) ** 1.6)) + scallop(r, x) // 2
        bot = h - 1 - (1 if r.random() < 0.3 else 0)
        if top >= bot:
            continue
        for y in range(top, bot + 1):
            g.blank(x, y, x, y, "#000000")
            if r.random() < 0.38:
                g.set(x, y, r.choice(":."), DOT_DIM)
        g.set(x, top, "_" if abs(u) < 0.35 else ("(" if u < 0 else ")"), EDGE)
        g.set(x, bot, "_", DOT)
    return g


def rays():
    """Light coming down through the gap: lines fanning out from it, longer each frame."""
    out = []
    w, h = 31, 16
    for k in range(4):
        g = Grid(w, h)
        n = 4 + 4 * k
        for dx in (-7, -4, -2, 0, 2, 4, 7):
            for y in range(min(n, h)):
                x = w // 2 + int(round(dx * y / 5.0))
                if 0 <= x < w and (y + dx) % 3 != 2:
                    ch = "|" if dx == 0 else ("/" if dx < 0 else "\\")
                    g.set(x, y, ch, RAY)
        out.append(g)
    return out


def main():
    pkg = sys.argv[1]
    os.makedirs(pkg, exist_ok=True)
    head = "// Generated by tools/build_scene17.py. Don't edit by hand; change the script and rebuild.\n"
    ex = Exporter(head)
    # him standing, then shading his eyes (scene 14's and 5's frames), the O cut out since the scene draws his ∆ there
    frames = [HERO[4], ["   │  ", " O_❄  ", "/|\\T  ", "/ \\   "]]
    xs, ys = [], []
    for fr in frames:
        for y, row in enumerate(fr):
            if "O" in row:
                xs.append(row.index("O"))
                ys.append(y)
                break
    blade = {"│": ICE_BLADE, "❄": ICE_BLADE, "T": ICE_BLADE}
    ex.piece("hero", frames_of([[row.replace("O", " ") for row in fr] for fr in frames], CHAR, blade))
    ex.value("headX", xs)
    ex.value("headY", ys)
    ex.piece("rays", rays())
    ex.piece("puffA", [puff((4, 3))])
    ex.piece("puffB", [puff((6, 5))])
    ex.piece("puffC", [puff((3, 2))])
    ex.piece("bankBack", [bank(False)])
    ex.piece("bankFront", [bank(True)])
    ex.value("bankW", BANK_W)
    ex.piece("sea", [cloud_sea(BANK_W, 7)])
    ex.piece("isleL", [island(30, 9, 191)])
    ex.piece("isleR", [island(24, 8, 192)])
    ex.piece("streak", frames_of([["|", "|"], ["|", "'"], ["'", "."]], "#ffffff"))
    # the empty cart and its stub of rail, laid in lengths
    ex.piece("cart", frames_of([["│¯¯¯¯│", "└()()┘"]], CART_RIM, {"(": CART_DIM, ")": CART_DIM}))
    rail = "".join("╤" if i % RAIL_LEN == 0 else "═" for i in range(RAIL_LEN * 3 + 1))
    ex.piece("rail", frames_of([[rail]], RAILC))
    ex.value("railLen", RAIL_LEN)
    size = ex.write(os.path.join(pkg, "Art17Up.txt"))
    print(f"Art17Up {size} bytes")


if __name__ == "__main__":
    main()
