"""Builds the art for scene 12 (the headless stand).

    python -I build_scene12.py <package dir>

Writes Art12Stand.txt: him without his head, his sword in the snow, the cut end of the whip and the crevasse.
The summit is scene 10's and the Ring scene 1's.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Grid, Exporter, frames_of, CHAR
from build_scene7 import SNOW, SNOW_DIM, SNOW_BACK, FOG_DIM, BACK, FRONT
from build_scene8 import build_hero, STEEL
from build_scene10 import feet, GOLD
import controller_frames as CTRLF
import whips

ICE_LIT = "#a8d4e6"
ICE_DIM = "#4a6a7a"
DARK = "#07090b"
WHIP_DIM = "#8a7438"         # the cut end, lying in the snow

CREV_X0, CREV_X1 = 163, 175  # the crevasse
CUT_U = 17                   # lash frame he cuts it on, lying along the snow
CUT_DX = -9                  # where the cut is, from the Controller's hand


def headless():
    """Scene 8's frames of him with the head taken off, plus new ones the same size: standing and walking
    empty-handed, and pushing like the game's Pushers do (theirs push left, this one pushes right)."""
    hero = build_hero()
    keep = [0, 1, 2, 3, 4, 5, 6, 15, 16]
    out = []
    for i in keep:
        g = hero[i]
        h = Grid(g.w, g.h)
        for y in range(g.h):
            for x in range(g.w):
                cell = g.c[y][x]
                if cell and cell[0] != "O":
                    h.c[y][x] = cell
        out.append(h)
    w, hh = hero[0].w, hero[0].h
    pad = lambda rows: [r.ljust(w) for r in rows]
    new = [pad(["", "", "/|\\", "/ \\"])]                                      # 9 standing, empty-handed
    new += [pad(["", "", "/|\\", leg]) for leg in (" >\\", " |\\", " |>", "/ \\")]     # 10-13 walking
    new += [pad(["", "", " /¯", leg]) for leg in ("/| ", "v| ", " |>", "/ \\")]        # 14-17 pushing
    grids = frames_of(new + [["", "", "", "".ljust(w)]], CHAR)[:-1]
    for g in grids:
        assert (g.w, g.h) == (w, hh), (g.w, g.h)
    return out + grids


def build_crevasse():
    """A crevasse across the shoulder, overhanging lips and ice walls going down into the cloud."""
    r = random.Random(121)
    x0 = CREV_X0 - 2
    w = CREV_X1 - CREV_X0 + 5
    top = int(math.floor(feet(CREV_X0))) - BACK
    bottom = int(math.floor(feet(CREV_X0))) + FRONT + 16
    g = Grid(w, bottom + 1)
    for y in range(top, bottom + 1):
        d = y - top
        a = CREV_X0 - x0 + int(1.2 * math.sin(d * 0.7)) + (1 if d > 8 else 0)
        b = CREV_X1 - x0 + int(1.1 * math.sin(d * 0.9 + 1)) - (1 if d > 10 else 0)
        for x in range(a + 1, b):
            g.blank(x, y, x, y, DARK)
            if d < 7 and r.random() < 0.12:
                g.set(x, y, r.choice("'.:"), ICE_DIM)
        col = ICE_LIT if d < 6 else (ICE_DIM if d < 12 else DARK)
        g.set(a, y, "\\" if d < 2 else r.choice("|)|:"), col)
        g.set(b, y, "/" if d < 2 else r.choice("|(|:"), col)
    # overhanging lips with icicles under them
    g.text(CREV_X0 - x0 - 2, top - 1, "_.-", SNOW)
    g.text(CREV_X1 - x0, top - 1, "-._", SNOW)
    for x, n in ((CREV_X0 - x0 + 1, 2), (CREV_X0 - x0 + 3, 1), (CREV_X1 - x0 - 2, 2)):
        for k in range(n):
            g.set(x, top + k, "V" if k == n - 1 else "|", ICE_LIT)
    return g, x0


def build_cut_whip():
    """The cut end of his whip lying in the snow, from the cut out to the tip."""
    g = frames_of(CTRLF.DOMINO + [CTRLF.DOMINO_BARE], GOLD)
    hand_y = CTRLF.DOMINO_HAND[1] - (g[0].h - 1)
    lg, lox, loy, crack = whips.lash(n=27, frames=22, ground=lambda dx: -0.79, hand_y=hand_y, dir=-1, col=GOLD,
                                     keep=8, v=2.0, gravity=0.05, scale=1.4)
    src = lg[CUT_U]
    cut = Grid(src.w, src.h)
    for y in range(src.h):
        for x in range(src.w):
            if src.c[y][x] and x - lox < CUT_DX:
                cut.c[y][x] = (src.c[y][x][0], WHIP_DIM)
    return cut


def main():
    pkg = sys.argv[1]
    os.makedirs(pkg, exist_ok=True)
    head = "// Generated by tools/build_scene12.py. Don't edit by hand; change the script and rebuild.\n"
    ex = Exporter(head)
    ex.piece("body", headless())
    crev, cx0 = build_crevasse()
    ex.piece("crevasse", [crev])
    ex.value("crevX", cx0)
    ex.value("crevX0", CREV_X0)
    ex.value("crevX1", CREV_X1)
    ex.piece("cutWhip", [build_cut_whip()])
    ex.value("cutU", CUT_U)
    ex.value("cutDX", CUT_DX)
    # his sword stuck point down in the snow
    ex.piece("sword", frames_of([["┼", "│"]], STEEL))
    n = ex.write(os.path.join(pkg, "Art12Stand.txt"))
    print(f"Art12Stand {n} bytes")


if __name__ == "__main__":
    main()
