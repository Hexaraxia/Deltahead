"""Builds the art for scene 13 (the Delta chest).

    python -I build_scene13.py <package dir>

Writes Art13Delta.txt: the chest, the ∆, the Ice Sword, and him without his head.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Exporter, frames_of, mirror, CHAR

# Ice Sword +15: the game's socketed sword with ice in the socket, in Legendary red
BLADE = "#ff2222"
CHEST = "#e7e3da"


# him facing right, six wide and five tall (the top row is for the sword held up), feet on the last row.
# his head gets taken off below but where it was is kept
EMPTY = [
    ["      ", "      ", " O    ", "/|\\   ", " >\\   "],      # 0-3 walking, empty-handed
    ["      ", "      ", " O    ", "/|\\   ", " |\\   "],
    ["      ", "      ", " O    ", "/|\\   ", " |>   "],
    ["      ", "      ", " O    ", "/|\\   ", "/ \\   "],
    ["      ", "      ", " O    ", "/|\\   ", "/ \\   "],      # 4 standing
    ["      ", "      ", "      ", "  _\\O ", " |\\/  "],     # 5 bent to the chest (the game's pickup)
    # 6-7 the game's pull: braced grip, then leaning back hard
    ["      ", "      ", "O     ", "\\──┐  ", "/ \\   "],
    ["      ", "      ", "O     ", "\\───┐ ", " \\\\   "],
    ["      ", "      ", " O/   ", "/|    ", "/ \\   "],      # 8 holding something up
]
ARMED = [
    ["      ", "   │  ", " O ❄  ", "/|\\T  ", " >\\   "],     # 9-12 walking with the sword
    ["      ", "   │  ", " O ❄  ", "/|\\T  ", " |\\   "],
    ["      ", "   │  ", " O ❄  ", "/|\\T  ", " |>   "],
    ["      ", "   │  ", " O ❄  ", "/|\\T  ", "/ \\   "],
    ["      ", "   │  ", " O ❄  ", "/|\\T  ", "/ \\   "],     # 13 standing with it
    ["   │  ", "   ❄  ", " O T  ", "/|/   ", " />   "],      # 14 the leap, the sword up over him
    ["      ", "    │ ", "    ❄ ", "  O T ", " /|/  "],       # 15 landing, crouched, the sword up beside him
    # 16-20 the game's pickup: bend (head short of it so it isn't hidden), grab the hilt, lift it overhead
    ["      ", "      ", "  O   ", " ¯/|  ", " |\\   "],
    ["      ", "      ", "      ", "  _\\O ", " |\\/  "],
    ["      ", "      ", "   │  ", "  _❄O ", " |\\T  "],
    ["      ", "    │ ", "   O❄ ", " ¯/|T ", " |\\   "],
    ["   │  ", "   ❄  ", " O T  ", "/|/   ", "/ \\   "],
]


def heads(frames):
    xs, ys = [], []
    for f in frames:
        for y, row in enumerate(f):
            if "O" in row:
                xs.append(row.index("O"))
                ys.append(y)
                break
    return xs, ys


def strip(frames):
    return [[row.replace("O", " ") for row in f] for f in frames]


def main():
    pkg = sys.argv[1]
    os.makedirs(pkg, exist_ok=True)
    head = "// Generated by tools/build_scene13.py. Don't edit by hand; change the script and rebuild.\n"
    ex = Exporter(head)
    blade = {"│": BLADE, "❄": BLADE, "T": BLADE}
    allf = EMPTY + ARMED
    # the arm's ─ and ┐ in the pulling frames are him, not a blade
    grids = frames_of(strip(EMPTY), CHAR) + frames_of(strip(ARMED), CHAR, blade)
    w = grids[0].w
    ex.piece("bodyR", grids)
    ex.piece("bodyL", mirror(grids))
    hx, hy = heads(allf)
    ex.value("headXR", hx)
    ex.value("headXL", [w - 1 - x for x in hx])
    ex.value("headY", hy)
    ex.value("bodyW", w)
    # chest frames: shut, lid up, open, ∆ torn out. uncropped since the rainbow runs across the page
    ex.piece("chest", frames_of([["     ", " ___ ", "╞─ ─╡", "└───┘"],
                                 [" ___ ", " │```", "╞─ ─╡", "└───┘"],
                                 ["     ", "     ", "╞─ ─╡", "└───┘"],
                                 ["     ", "     ", "╒─,─╕", "└───┘"]], CHEST), crop=False)
    ex.piece("delta", frames_of([["∆"]], CHEST))
    # the sword stuck upright where it fell, like the game's dropped one
    ex.piece("item", frames_of([["│", "❄", "T"]], BLADE))
    n = ex.write(os.path.join(pkg, "Art13Delta.txt"))
    print(f"Art13Delta {n} bytes; heads R {hx} / {hy}")


if __name__ == "__main__":
    main()
