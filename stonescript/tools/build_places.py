"""Builds the places the delta constellation is seen from in scene 16's montage.

    python -I build_places.py <package dir>

Writes Art16Places.txt from the game's own art (place_frames.py) at night: the Icy Ridge with its dunes, snowfield
and Ki creatures, and the Cross Deadwood River canyon with its tentacle and frog.
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_scene1 import Grid, Exporter, frames_of
import place_frames as P

MOON = "#e8e4d4"
STAR = "#9aa6b0"
SNOW = "#dfe6ea"
SNOW_DIM = "#9aa6ac"
SNOW_BACK = "#6b7680"
FILL = "#090b0d"
WALL = "#7c7c7c"
WALL_DIM = "#4e4e4e"
WATER = "#5e7484"
TENTACLE = "#7a6e94"
FROG = "#8fae6a"


def game_grid(rows, color, see_through_spaces=False):
    """A piece of game art in one color, or color(x, y, ch) if color is a function."""
    w = max(len(r) for r in rows)
    g = Grid(w, len(rows))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                continue
            if ch == " ":
                if not see_through_spaces:
                    g.blank(x, y, x, y, FILL)
                continue
            g.set(x, y, ch, color(x, y, ch) if callable(color) else color)
    return g


def ridge_sky():
    # the moon is the cluster round the middle, the rest are stars. see-through so the shared sky shows
    def col(x, y, ch):
        return MOON if 18 <= x <= 40 and 1 <= y <= 8 and ch != "." else STAR
    g = game_grid(P.RIDGE_SKY, col, see_through_spaces=True)
    # keep the moon solid (column 27, row 2) so no star shows through it
    for j, row in enumerate(P.RIVER_MOON):
        for i, ch in enumerate(row):
            if ch == " ":
                g.blank(27 + i, 2 + j, 27 + i, 2 + j, FILL)
    return g


def ridge_dunes():
    def col(x, y, ch):
        return SNOW_DIM if ch in "'·.`:" else SNOW
    return [game_grid(f, col) for f in P.RIDGE_DUNES]


def ridge_field(w, h):
    """The snowfield in front of the dunes where the creatures walk, more texture at the back."""
    r = random.Random(161)
    g = Grid(w, h)
    g.blank(0, 0, w - 1, h - 1, FILL)
    for y in range(h):
        for x in range(w):
            p = r.random()
            if p < 0.09 - y * 0.006:
                g.set(x, y, r.choice(".'`-_"), SNOW_DIM if y < 3 else SNOW_BACK)
    return g


def river():
    rows = [list(r) for r in P.RIVER]
    # take the one crossing off the bank, his canoe stays beached
    for x, y in ((29, 19), (28, 20), (29, 20), (30, 20), (28, 21), (29, 21), (30, 21)):
        if y < len(rows) and x < len(rows[y]):
            rows[y][x] = " "
    rows = ["".join(r) for r in rows]

    def col(x, y, ch):
        if 60 <= x <= 78 and 0 <= y <= 9:
            return MOON
        if ch in "-~" and 37 <= x <= 102 and y >= 10:
            return WATER
        return WALL if ch in "|/\\_`´,'-.!:;" else WALL_DIM
    g = game_grid(rows, col)
    # see-through sky so the stars and constellation show over the rims, moon stays solid
    for y in range(9):
        for x in range(g.w):
            c = g.c[y][x]
            if c and c[0] == " " and not (60 <= x <= 78):
                g.c[y][x] = None
    return g


def main():
    pkg = sys.argv[1]
    ex = Exporter("// Generated by tools/build_places.py. Don't edit by hand; change the script and rebuild.\n")
    ex.piece("ridgeSky", [ridge_sky()])
    ex.piece("ridgeDunes", ridge_dunes())
    ex.piece("ridgeField", [ridge_field(130, 13)])
    ex.piece("river", [river()])
    ex.piece("riverStars", [game_grid(f, "#c8ccd4", see_through_spaces=True) for f in P.RIVER_STARS])
    ex.piece("tentacle", [game_grid(f, TENTACLE, see_through_spaces=True) for f in P.TENTACLE])
    # the frog blinking, then staring with its mouth open
    frog = [list(f) for f in P.FROG]
    stare = list(P.FROG[0])
    stare[3] = stare[3].replace(".-)", ".O)")
    frog.append(stare)
    ex.piece("frog", [game_grid(f, FROG) for f in frog])
    n = ex.write(os.path.join(pkg, "Art16Places.txt"))
    print(f"Art16Places {n} bytes")


if __name__ == "__main__":
    main()
